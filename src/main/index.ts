// Protocol handler
function handleProtocol(url: string) {
  log.info("Handling protocol url", url);
  const urlPaths = url.split("://")[1];
  if (urlPaths) {
    const paths = urlPaths.split("/");
    if (paths.length > 0) {
      switch (paths[0]) {
        case "control": {
          const command = paths[1];
          if (ytmView && ["playPause", "next", "previous"].includes(command)) {
            ytmView.webContents.send("remoteControl:execute", command);
          }
          break;
        }
        case "focus": {
          showMainWindow();
          break;
        }
        case "play": {
          if (paths.length >= 2) {
            const videoId = paths[1];
            const playlistId = paths[2];

            if (ytmView) {
              ytmView.webContents.send("remoteControl:execute", "navigate", {
                watchEndpoint: {
                  videoId: videoId,
                  playlistId: playlistId
                }
              });
            }
          }
        }
      }
    }
  }
}

