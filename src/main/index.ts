function shouldDisableUpdates() {
  // Updates come from this build's own repository (see YTMD_UPDATE_FEED_OWNER).
  // update.electronjs.org only serves public repositories, so this stays without effect
  // until the repository is public and has releases, which the error handler below tolerates.
  // macOS needs a code signature and Linux is not supported by the update server.
  if (process.platform !== "win32") return true;
  return false;
}

// Configure the autoupdater
// macOS cannot use the autoUpdater without a code signature at this time
if (app.isPackaged && !shouldDisableUpdates() && !YTMD_DISABLE_UPDATES) {
  const updateServer = "https://update.electronjs.org";
  const updateFeed = `${updateServer}/${YTMD_UPDATE_FEED_OWNER}/${YTMD_UPDATE_FEED_REPOSITORY}/${process.platform}-${process.arch}/${app.getVersion()}`;

  autoUpdater.setFeedURL({
    url: updateFeed
  });
  autoUpdater.on("checking-for-update", () => {
    if (appLaunchUpdateCheck) memoryStore.set("ytmViewLoadingStatus", "Checking for updates...");
    if (settingsWindow) settingsWindow.webContents.send("app:checkingForUpdates");
  });
  autoUpdater.on("update-available", () => {
    log.info("Application update available");
    memoryStore.set("appUpdateAvailable", true);
    appUpdateAvailable = true;
    if (appLaunchUpdateCheck) memoryStore.set("ytmViewLoadingStatus", "Downloading update...");
    if (settingsWindow) settingsWindow.webContents.send("app:updateAvailable");
  });
  autoUpdater.on("update-not-available", () => {
    if (appLaunchUpdateCheck) appLaunchUpdateCheck = false;
    if (settingsWindow) settingsWindow.webContents.send("app:updateNotAvailable");
  });
  autoUpdater.on("update-downloaded", () => {
    log.info("Application update downloaded");
    appUpdateDownloaded = true;
    memoryStore.set("appUpdateDownloaded", true);
    if (appLaunchUpdateCheck) autoUpdater.quitAndInstall();
    if (settingsWindow) settingsWindow.webContents.send("app:updateDownloaded");
  });
  autoUpdater.on("error", () => {
    if (appLaunchUpdateCheck) appLaunchUpdateCheck = false;
    if (settingsWindow) settingsWindow.webContents.send("app:updateNotAvailable");
  });
  log.info("Setup application updater");

  setInterval(
    () => {
      autoUpdater.checkForUpdates();
    },
    1000 * 60 * 15
  );
} else {
  memoryStore.set("autoUpdaterDisabled", true);
}

// The native window buttons (minimize, maximize, close) are drawn by the OS on this colour, so it
// has to follow the theme or the title bar ends in a black box next to a tinted bar
const titleBarColors: Record<ThemePreset, string> = {
  [ThemePreset.Default]: "#111111",
  [ThemePreset.Midnight]: "#110f1b",
  [ThemePreset.Ocean]: "#071921",
  [ThemePreset.Forest]: "#0f1a12",
  [ThemePreset.Dynamic]: "#111111"
};

// The dynamic theme's current colours (from the album art of the song that is playing)
let dynamicPalette: ThemePalette | null = null;
let dynamicPaletteSource: string | null = null;

function titleBarOverlayFor(theme: ThemePreset) {
  const color = theme === ThemePreset.Dynamic && dynamicPalette ? dynamicPalette.background : (titleBarColors[theme] ?? titleBarColors[ThemePreset.Default]);
  return { color, symbolColor: "#BBBBBB", height: 36 };
}

/** Recolours everything for the song that is playing, when the dynamic theme is selected. */
function updateDynamicPalette(state: PlayerState) {
  if (store.get("appearance").theme !== ThemePreset.Dynamic) return;
  const thumbnails = state.videoDetails?.thumbnails;
  if (!thumbnails?.length) return;
  // The first data of a song can come without the album art, so the art decides - not only the song
  const source = `${state.videoDetails.id}:${thumbnails[0].url}`;
  if (source === dynamicPaletteSource) return;
  dynamicPaletteSource = source;
  void paletteFromThumbnails(thumbnails).then(palette => {
    if (!palette || source !== dynamicPaletteSource) return;
    dynamicPalette = palette;
    builtInTheme.setDynamicPalette(palette);
    memoryStore.set("dynamicPalette", palette);
    applyTitleBarTheme(ThemePreset.Dynamic);
  });
}

function applyTitleBarTheme(theme: ThemePreset) {
  if (process.platform === "linux") return; // setTitleBarOverlay is Windows/macOS only
  for (const window of [mainWindow, settingsWindow]) {
    if (window && !window.isDestroyed()) window.setTitleBarOverlay(titleBarOverlayFor(theme));
  }
}

