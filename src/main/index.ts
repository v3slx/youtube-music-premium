log.errorHandler.startCatching({
  showDialog: false,
  onError({ error, errorName, processType, versions }) {
    if (applicationExited) return;
    if (processType === "renderer") return;

    // A promise nobody handled (a failed network request in an integration, for example) is
    // logged, but must not take the whole app down the way an uncaught exception does
    if (errorName?.includes("rejection")) {
      log.error("Unhandled promise rejection", error);
      return false;
    }

    if (stateSaverInterval) clearInterval(stateSaverInterval);

    // This just ensures AggregateError sub errors is being unwrapped properly and logged
    if (error instanceof AggregateError) {
      log.error(error);
      for (const subError of error.errors) {
        log.error(subError);
      }
    } else {
      log.error(error);
    }

    let result = 1; // Default to Exit

    const dialogMessage =
      `Environment Details:\n    ${versions.app}\n    ${versions.electron}\n    ${versions.os}\n\n` +
      `Name: ${error.name}\nMessage: ${error.message}\nCause: ${error.cause ?? "Unknown"}\n\n` +
      `${error.stack}`;

    if (!app.isReady()) {
      dialog.showErrorBox(`${app.getName()} Crashed`, `Application crashed before ready\n\n${dialogMessage}`);
    } else {
      const options = ["Copy to Clipboard and Exit", "Exit"];
      if (!app.isPackaged) {
        options.push("Copy to Clipboard and Continue", "Continue");
      }

      result = dialog.showMessageBoxSync({
        title: "Error",
        message: `${app.getName()} Crashed`,
        detail: dialogMessage,
        type: "error",
        buttons: options
      });

      // Copy to Clipboard
      if (result === 0 || result === 2) {
        clipboard.writeText(`${app.getName()} Crashed\n\n${dialogMessage}`);
      }
    }

    // Exit
    if (result === 0 || result === 1) {
      applicationExited = true;
      app.exit(1);
    }
  }
});
